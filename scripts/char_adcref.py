#!/usr/bin/env python3
"""Window-ADC reference: VREF/2 resistor string (DAC + window thresholds) and the VOUT/2 divider
(VOUT/2 because the comparators run on the VIN rail, DECISIONS D26).

String: 520 equal high_po_1p41 units (L = 3 um) between an ideal 1.300 V reference and ground,
2.5 mV per unit. For VREF code c the DAC tap is node 2c (VREF/2 = c x 5 mV, 10 mV at VOUT)
and the 15 window thresholds are nodes 2c + 2i - 15 (i = 0..14): half-codes, (i - 7.5) LSB, so the
ADC LSB is a resistor ratio and tracks the poly sheet-resistance corner.
Divider: VOUT -> VOUT/2 with 6 matched xhigh_po_5p73 units (L = 16 um, 5.6 kohm), 3 on top, 3 below,
and a 10 pF MIM decoupling cap on VOUT/2 (absorbs the 15 comparators' kickback; tau ~85 ns).

Monte Carlo (mismatch, tt, 27 C): threshold errors in ADC LSB at codes 100, 180, 250 (1.0, 1.8,
2.5 V), VREF/3 tap error, divider ratio error. Corners: sheet-resistance corner effect on the
ratio (should be none). Writes spice/adc_ref.spice and results/phase3/adcref.json.
"""
import numpy as np

from spicelib import CORNERS, SPICE_DIR, header, include, pmap, run, save

NSEG = 520                               # tap 2c+13 must exist for c = 250 (node 513)
VTOP = NSEG * (10e-3 / 2) / 2          # 1.300 V
LSB_C = 10e-3 / 2                       # ADC LSB at the comparator (5 mV)
CODES = [100, 180, 250]


def write_netlist():
    lines = ["* Window-ADC reference (generated by scripts/char_adcref.py)",
             "* adc_string: 520 x high_po_1p41 (L = 3 um); node k = k x 2.5 mV for a 1.300 V top.",
             ".subckt adc_string top vss"]
    for k in range(NSEG):
        a = "vss" if k == 0 else f"n{k}"
        b = "top" if k == NSEG - 1 else f"n{k + 1}"
        lines.append(f"XR{k} {b} {a} vss sky130_fd_pr__res_high_po_1p41 l=3 mult=1")
    lines.append(".ends")
    lines += ["* adc_div: VOUT/2 divider, 6 x xhigh_po_5p73 (L = 16 um, 5.6 kohm), 10 pF MIM on vdiv",
              "* (1.41 x 4 um units gave a 0.6 % ratio sigma; 16x the area for the same impedance)",
              ".subckt adc_div vout vdiv vss"]
    nodes = ["vout", "d1", "d2", "vdiv", "d4", "d5", "vss"]
    for k in range(6):
        lines.append(f"XD{k} {nodes[k]} {nodes[k + 1]} vss sky130_fd_pr__res_xhigh_po_5p73 l=16 mult=1")
    lines.append("XCD vdiv vss sky130_fd_pr__cap_mim_m3_1 w=70 l=70 mf=1")
    lines.append(".ends")
    (SPICE_DIR / "adc_ref.spice").write_text("\n".join(lines) + "\n")


def one(args):
    corner, seed = args
    mc = seed > 0
    tag = f"adcref_{corner}_{seed}"
    taps = sorted({2 * c + 2 * i - 15 for c in CODES for i in range(15)} | {2 * c for c in CODES})
    prints = " ".join(f"v(x1.n{k})" for k in taps)
    seedline = f"setseed {seed}\nreset\n" if mc else ""
    n = header(corner, 27, mc=mc, title=tag) + include("adc_ref.spice") + f"""
VT top 0 {VTOP}
X1 top 0 adc_string
VO vout 0 1.8
X2 vout vdiv 0 adc_div
.control
{seedline}op
print {prints} v(vdiv)
quit
.endc
.end
"""
    v = run(n, tag)
    res = {"corner": corner, "seed": seed, "div_ratio": v["v(vdiv)"] / 1.8}
    for c in CODES:
        th = np.array([v[f"v(x1.n{2 * c + 2 * i - 15})"] for i in range(15)])
        ideal = c * LSB_C + (np.arange(15) - 7.5) * LSB_C
        res[f"th_err_lsb_{c}"] = ((th - ideal) / LSB_C).tolist()
        res[f"vref_err_lsb_{c}"] = (v[f"v(x1.n{2 * c})"] - c * LSB_C) / LSB_C
    return res


if __name__ == "__main__":
    write_netlist()
    rows = pmap(one, [("tt", s) for s in range(1, 101)] + [(c, 0) for c in CORNERS])
    mc = [r for r in rows if r["seed"] > 0]
    out = {"rows": rows, "source": "scripts/char_adcref.py (ngspice)", "nseg": NSEG, "vtop": VTOP}
    for c in CODES:
        e = np.array([r[f"th_err_lsb_{c}"] for r in mc])
        dnl = np.diff(e, axis=1)            # threshold spacing error in LSB
        out[f"code{c}"] = {"th_err_sigma_lsb": float(e.std()), "th_err_max_lsb": float(np.abs(e).max()),
                           "spacing_err_sigma_lsb": float(dnl.std()),
                           "vref_err_sigma_lsb": float(np.std([r[f'vref_err_lsb_{c}'] for r in mc]))}
        print(f"code {c}: threshold error sigma {e.std():.4f} LSB (max {np.abs(e).max():.4f}); "
              f"spacing sigma {dnl.std():.4f} LSB")
    dr = np.array([r["div_ratio"] for r in mc])
    out["div_ratio_mean"] = float(dr.mean())
    out["div_ratio_sigma_rel"] = float(dr.std() / dr.mean())
    out["div_ratio_corners"] = {r["corner"]: r["div_ratio"] for r in rows if r["seed"] == 0}
    print(f"divider ratio {dr.mean():.6f} (nominal 0.5), sigma {dr.std() / dr.mean() * 100:.4f} % "
          f"(= {dr.std() / dr.mean() * 1800:.2f} mV at VOUT 1.8 V); corners {out['div_ratio_corners']}")
    save("adcref", out)
