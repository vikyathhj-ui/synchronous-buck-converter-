#!/usr/bin/env python3
"""Calibrated DPWM fine stage (spice/dpwm_cal.spice, written here): main 64-element line + 64:1
mux + SR latch, and the 72-element replica line used by the controller's TDC calibration.

Per condition, two simulations:
  A: an edge into the replica line (90 ns: 63 elements take 44 ns at the slowest corner); N = number of replica taps crossed within one clock period
     (what the controller's TDC counts), and the mean element delay of both lines.
  B: 8 switching periods with tap_sel = (f * 16N + 64) >> 7 for f = 0..7 (the RTL mapping with
     a settled n_cal = 16N); ton(f) measured; DNL/INL in LSB = Tclk/8, including the coarse
     boundary step Tclk - (ton(7) - ton(0)).
  pvt : every corner x temperature x VDD 1.62/1.80/1.98
  mc  : 50 mismatch samples at tt / 27 C / 1.8 V (main and replica lines mismatch independently)
Writes spice/dpwm_cal.spice and results/phase3/dpwm_cal.json.
"""
import sys

import numpy as np

from spicelib import CORNERS, PDK, SPICE_DIR, TEMPS, header, include, pmap, run, save

HD = PDK / "libs.ref" / "sky130_fd_sc_hd" / "spice" / "sky130_fd_sc_hd.spice"
TCLK = 1 / 64e6
LSB = TCLK / 8
TP = 100e-9
NMAIN, NREP = 64, 72


def write_netlist():
    L = ["* Calibrated DPWM fine stage (1.8 V, hd cells), generated by scripts/char_dpwm_cal.py.",
         "* dpwm_cal: main line of 64 dlygate4sd3_1 + 64:1 mux tree (tap_sel = t5..t0) + NOR SR latch.",
         "*   pwm_set sets the latch (HS on); pwm_rst enters the line; the selected tap resets it.",
         "* tdc_line: replica line of 72 elements; the controller launches an edge and samples q1..q72",
         "*   one clock later; the number of ones is N (elements per clock period).",
         ".subckt dpwm_cal pwm_set pwm_rst t0 t1 t2 t3 t4 t5 hs_pwm vdd vss"]
    for k in range(NMAIN):
        a = "pwm_rst" if k == 0 else f"m{k}"
        L.append(f"XE{k} {a} vss vss vdd vdd m{k + 1} sky130_fd_sc_hd__dlygate4sd3_1")
    nodes = ["pwm_rst"] + [f"m{k}" for k in range(1, NMAIN)]
    lvl = 0
    while len(nodes) > 1:
        nxt = []
        for i in range(0, len(nodes), 2):
            o = "rst_d" if len(nodes) == 2 else f"x{lvl}_{i // 2}"
            L.append(f"XM{lvl}_{i // 2} {nodes[i]} {nodes[i + 1]} t{lvl} vss vss vdd vdd {o} sky130_fd_sc_hd__mux2_1")
            nxt.append(o)
        nodes, lvl = nxt, lvl + 1
    L += ["XL1 rst_d qb vss vss vdd vdd hs_pwm sky130_fd_sc_hd__nor2_1",
          "XL2 pwm_set hs_pwm vss vss vdd vdd qb sky130_fd_sc_hd__nor2_1", ".ends",
          ".subckt tdc_line launch " + " ".join(f"q{k}" for k in range(1, NREP + 1)) + " vdd vss"]
    for k in range(NREP):
        a = "launch" if k == 0 else f"q{k}"
        L.append(f"XR{k} {a} vss vss vdd vdd q{k + 1} sky130_fd_sc_hd__dlygate4sd3_1")
    L.append(".ends")
    (SPICE_DIR / "dpwm_cal.spice").write_text("\n".join(L) + "\n")


def tap_of(f, n):
    return (f * 16 * n + 64) >> 7


def sim(corner, temp, vdd, mc=False, seed=0):
    tag = f"dcal_{corner}_{temp}_{vdd}_{'mc' + str(seed) if mc else 'nom'}"
    seedline = f"setseed {seed}\nreset\n" if mc else ""
    # ---- A: replica-line TDC and element delays
    qs = " ".join(f"q{k}" for k in range(1, NREP + 1))
    meas = "\n".join(f"meas tran tq{k} when v(q{k})={vdd / 2} rise=1" for k in range(1, NREP + 1))
    measm = "\n".join(f"meas tran tm{k} when v(x1.m{k})={vdd / 2} rise=1" for k in (1, 32, 63))
    na = header(corner, temp, mc=mc, title=tag + "_A") + include("dpwm_cal.spice") + f""".include {HD}
VDD vdd 0 {vdd}
VL launch 0 pwl(0 0 2n 0 2.05n {vdd})
XR launch {qs} vdd 0 tdc_line
VS pwm_set 0 0
X1 pwm_set launch 0 0 0 0 0 0 hs_pwm vdd 0 dpwm_cal
.control
{seedline}tran 0.05n 90n 0 0.1n
meas tran tl when v(launch)={vdd / 2} rise=1
{meas}
{measm}
quit
.endc
.end
"""
    va = run(na, tag + "_A")
    t0 = va["tl"]
    tq = np.array([va.get(f"tq{k}", np.inf) - t0 for k in range(1, NREP + 1)])
    n = int(np.sum(tq < TCLK))
    t_rep = float((tq[NREP - 1] - tq[0]) / (NREP - 1)) if np.isfinite(tq[-1]) else float(tq[n - 1] / n)
    t_main = float((va["tm63"] - va["tm1"]) / 62)
    # ---- B: calibrated DPWM, f = 0..7 with the RTL tap mapping
    taps = [tap_of(f, n) for f in range(8)]
    srcs = []
    for b in range(6):
        pts = []
        for k in range(8):                         # period 0 is a warm-up (latch power-up state)
            lvl = vdd * ((taps[k] >> b) & 1)
            pts += [f"{(k + 1) * TP + 1e-9}", f"{lvl}", f"{(k + 2) * TP}", f"{lvl}"]
        srcs.append(f"VT{b} t{b} 0 pwl(0 0 " + " ".join(pts) + ")")
    measb = "\n".join(f"meas tran ton{k} trig v(hs_pwm) val={vdd / 2} rise=1 td={(k + 1) * TP + 5e-9} "
                      f"targ v(hs_pwm) val={vdd / 2} fall=1 td={(k + 1) * TP + 5e-9}" for k in range(8))
    nb = header(corner, temp, mc=mc, title=tag + "_B") + include("dpwm_cal.spice") + f""".include {HD}
VDD vdd 0 {vdd}
VSET pwm_set 0 pulse(0 {vdd} 10n 50p 50p {TCLK - 100e-12} {TP})
VRST pwm_rst 0 pulse(0 {vdd} {10e-9 + 2 * TCLK} 50p 50p {TCLK - 100e-12} {TP})
{chr(10).join(srcs)}
X1 pwm_set pwm_rst t0 t1 t2 t3 t4 t5 hs_pwm vdd 0 dpwm_cal
.control
{seedline}tran 0.05n {9 * TP} 0 0.1n
{measb}
quit
.endc
.end
"""
    vb = run(nb, tag + "_B")
    ton = np.array([vb[f"ton{k}"] for k in range(8)])
    steps = np.append(np.diff(ton), TCLK - (ton[7] - ton[0]))
    return {"corner": corner, "temp": temp, "vdd": vdd, "seed": seed, "n": n, "t_rep": t_rep, "t_main": t_main,
            "taps": taps, "ton": ton.tolist(), "dnl": (steps / LSB - 1).tolist(),
            "inl": ((ton - ton[0]) / LSB - np.arange(8)).tolist(),
            "max_step_mv_vin36": float(steps.max() * 1e6 * 3.6 * 1e3)}


def pvt_one(a):
    return sim(*a)


def mc_one(seed):
    return sim("tt", 27, 1.8, mc=True, seed=seed)


if __name__ == "__main__":
    write_netlist()
    what = sys.argv[1] if len(sys.argv) > 1 else "all"
    import json, pathlib
    path = pathlib.Path(__file__).resolve().parents[1] / "results" / "phase3" / "dpwm_cal.json"
    data = json.loads(path.read_text()) if path.exists() else {}
    if what in ("pvt", "all"):
        rows = pmap(pvt_one, [(c, t, v) for c in CORNERS for t in TEMPS for v in (1.62, 1.8, 1.98)])
        data["pvt"] = rows
        dn = [d for r in rows for d in r["dnl"]]
        print(f"PVT: N {min(r['n'] for r in rows)}..{max(r['n'] for r in rows)}; DNL {min(dn):+.3f}..{max(dn):+.3f} LSB; "
              f"max output step at VIN 3.6 V {max(r['max_step_mv_vin36'] for r in rows):.2f} mV")
    if what in ("mc", "all"):
        rows = pmap(mc_one, range(1, 51))
        data["mc"] = rows
        dn = np.array([r["dnl"] for r in rows])
        print(f"MC: DNL sigma {dn.std():.3f} LSB, max |DNL| {np.abs(dn).max():.3f} LSB; "
              f"max output step at VIN 3.6 V {max(r['max_step_mv_vin36'] for r in rows):.2f} mV")
    data["source"] = "scripts/char_dpwm_cal.py (ngspice)"
    save("dpwm_cal", data)
