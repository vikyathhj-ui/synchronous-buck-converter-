#!/usr/bin/env python3
"""Write spice/models/sky130_mini.lib: the sky130A corner sections (tt ff ss sf fs) restricted to the
devices this design uses. Loading the full sky130.lib.spice takes about a minute per ngspice run;
this file takes a few seconds. It only .includes the installed PDK files (absolute paths), it does
not copy them. Monte Carlo mismatch works as in the PDK (.param mc_mm_switch=1 after .lib).
"""
import os
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[1]
PDK = pathlib.Path(os.environ.get("PDK_ROOT", "/foss/pdks")) / os.environ.get("PDK", "sky130A")
NG = PDK / "libs.tech" / "ngspice"
KEEP = ["nfet_01v8_", "pfet_01v8_", "pfet_01v8_hvt", "pfet_01v8_lvt", "nfet_g5v0d10v5_", "pfet_g5v0d10v5_", "nfet_05v0_nvt_"]
DROP = ["esd_", "nfet_01v8_lvt"]


def device_includes(corner):
    out = []
    for line in (NG / "corners" / f"{corner}.spice").read_text().splitlines():
        m = re.match(r'\.include\s+"(.+)"', line.strip())
        if not m:
            continue
        inc = m.group(1)
        name = pathlib.Path(inc).name
        path = pathlib.Path(os.path.normpath(NG / "corners" / inc))
        if "sky130_fd_pr__" in name:
            dev = name.split("sky130_fd_pr__")[1]
            if any(k in dev for k in KEEP) and not any(d in dev for d in DROP):
                out.append(path)
        elif inc.endswith("nonfet.spice") or inc.endswith("all.spice"):
            out.append(path)
    return out


def main():
    full = (NG / "sky130.lib.spice").read_text()
    lines = ["* Reduced sky130A model library (generated by scripts/make_minilib.py; includes PDK files only)"]
    for corner in ("tt", "ff", "ss", "sf", "fs"):
        sec = re.search(rf"^\.lib {corner}\n(.*?)^\.endl {corner}", full, re.S | re.M).group(1)
        lines.append(f".lib {corner}")
        lines.append(".param mc_mm_switch=0")
        lines.append(".param mc_pr_switch=0")
        for inc in device_includes(corner):
            lines.append(f'.include "{inc}"')
        for m in re.finditer(r'\.include\s+"(r\+c/[^"]+|corners/[^/"]+/specialized_cells\.spice)"', sec):
            lines.append(f".include \"{os.path.normpath(NG / m.group(1))}\"")
        lines.append(f".endl {corner}")
    out = ROOT / "spice" / "models" / "sky130_mini.lib"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    print(out, sum(1 for l in lines if l.startswith(".include")), "includes")


if __name__ == "__main__":
    main()
